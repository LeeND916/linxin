def intensity_to_bucket(x: float) -> str:
    """将连续 intensity 值映射为三个离散桶之一。

    0.0 ~ 0.33 → intensity_low
    0.34 ~ 0.66 → intensity_mid
    0.67 ~ 1.0 → intensity_high
    """
    if x < 0.34:
        return "intensity_low"
    elif x < 0.67:
        return "intensity_mid"
    else:
        return "intensity_high"

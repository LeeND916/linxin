def pose_desc_for_action(name):
    """给定活动名，返回一句肖像生图姿态描述。

    优先级：COMFYUI_POSE_BY_NAME 精准名 → 关键词语义分类（首个命中）→ 通用兜底。
    """
    if not name:
        return _GENERIC_POSE
    exact = COMFYUI_POSE_BY_NAME.get(name)
    if exact:
        return exact
    for kws, desc in _KEYWORD_POSE:
        for k in kws:
            if k and k in name:
                return desc
    return _GENERIC_POSE

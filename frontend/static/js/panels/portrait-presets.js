/**
 * 词库后端化（P2-D）：页面加载后拉取后端词库 /api/photo/vocab，
 * 用后端返回的同名分类覆盖前端内置词库（后端未提供的分类保留前端内置）。
 * 例外：画风定调(style)分类不再从后端覆盖，统一使用前端内置 18 种画风
 * （含动漫/彩绘/赛博朋克等混合画风），以恢复此前的多画风选择。
 */
async function loadPortraitVocab() {
    try {
        const resp = await fetch('/api/photo/vocab');
        const data = await resp.json();
        if (data && data.success && data.vocab && typeof data.vocab === 'object') {
            for (const k of Object.keys(data.vocab)) {
                // 画风定调(style)改用前端内置 18 种画风，不再用后端写实向覆盖，
                // 以恢复动漫/彩绘/赛博朋克等混合画风选择。其余分类仍可从后端覆盖。
                if (k === 'style') continue;
                const v = data.vocab[k];
                if (v && Array.isArray(v.subGroups)) {
                    PORTRAIT_VOCAB[k] = v;
                }
            }
            // 若肖像面板已打开，触发重渲染以应用新词库
            if (typeof PortraitPanel !== 'undefined' && PortraitPanel._renderVocab) {
                try { PortraitPanel._renderVocab(); } catch (e) { /* 忽略 */ }
            }
        }
    } catch (e) {
        console.warn('[PortraitVocab] 拉取后端词库失败，回退内置词库', e);
    }
}
document.addEventListener('DOMContentLoaded', loadPortraitVocab);


